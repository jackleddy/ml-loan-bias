"""
Runner for the machine-learning extension studies
=================================================

WHAT THIS FILE DOES
    Runs any or all of the five extension studies, then writes an index page,
    reports/ml_extensions/README.md, listing every chart, the study that made it,
    and each study's key numbers. Start there when looking for a chart's source.

    Study (--parts name)  File                    Question it answers
    --------------------  ----------------------  ------------------------------------------
    bias_variance         bias_variance.py        Is the model too simple or too complex?
    high_priced           high_priced.py          Can we spot officially high-priced loans?
    proxy                 proxy_test.py           Can the inputs secretly reveal demographics?
    interpret             interpretability.py     What does the model pay attention to?
    fairness              fairness_tradeoff.py    How much accuracy does a fairness rule cost?

HOW TO RUN (from the repository root, after scripts/prepare_data.py has run)
    .\\.venv\\Scripts\\python.exe scripts/run_ml_extensions.py                       (all five)
    .\\.venv\\Scripts\\python.exe scripts/run_ml_extensions.py --parts proxy fairness (just some)

VISUALS PRODUCED
    None directly; each study file lists its own charts at the top. This file
    writes the index page README.md that maps every chart to its study.
"""
from __future__ import annotations

import time

from . import bias_variance, fairness_tradeoff, high_priced, interpretability, proxy_test
from .common import log
from .ml_shared import output_dir, read_part_summaries

# Study name -> (source file, function that runs it). Order = order they run in.
PARTS = {
    "bias_variance": ("bias_variance.py", bias_variance.run),
    "high_priced": ("high_priced.py", high_priced.run),
    "proxy": ("proxy_test.py", proxy_test.run),
    "interpret": ("interpretability.py", interpretability.run),
    "fairness": ("fairness_tradeoff.py", fairness_tradeoff.run),
}


def format_value(value):
    """Round numbers for display: shares under 1 keep 3 decimals, larger values keep 2."""
    if isinstance(value, float):
        return f"{value:.3f}" if abs(value) < 1 else f"{value:,.2f}"
    return str(value)


def findings_lines(findings, indent=0):
    """Turn a (possibly nested) dictionary of key numbers into Markdown bullet points."""
    lines = []
    for key, value in findings.items():
        prefix = "  " * indent + f"- {key.replace('_', ' ')}"
        if isinstance(value, dict):
            lines.append(prefix + ":")
            lines += findings_lines(value, indent + 1)
        else:
            lines.append(f"{prefix}: {format_value(value)}")
    return lines


def write_index(config):
    """Write reports/ml_extensions/README.md from every study summary saved so far."""
    files = {name: source for name, (source, _) in PARTS.items()}
    lines = [
        "# Machine-learning extension studies",
        "",
        "Generated by `scripts/run_ml_extensions.py`. Each section lists the charts a study produced",
        "and the source file (in `loanfair/`) that made them. Units: bp = basis points (100 bp = 1 percentage point).",
        "",
    ]
    for summary in read_part_summaries(config):
        lines += [f"## {summary['title']}", "", f"Source: `loanfair/{files.get(summary['part'], '?')}`", "", "| Chart | What it shows |", "|---|---|"]
        lines += [f"| `{name}` | {description} |" for name, description in summary["figures"].items()]
        lines += ["", "Key numbers:", ""] + findings_lines(summary["findings"]) + [""]
    (output_dir(config) / "README.md").write_text("\n".join(lines), encoding="utf-8")


def run(config, parts=None):
    """Run the chosen studies (default: all of them) and refresh the index page."""
    parts = list(PARTS) if parts is None else parts
    unknown = set(parts) - set(PARTS)
    if unknown:
        raise ValueError(f"Unknown extension studies: {sorted(unknown)}")
    for name in parts:
        start = time.time()
        log(f"=== Extension study: {name} ===")
        PARTS[name][1](config)
        log(f"=== {name} finished in {(time.time() - start) / 60:.1f} minutes ===")
        # Refresh the index after every study, so finished results are listed even if a later one fails.
        write_index(config)
    log(f"Charts, tables, and README.md saved in {output_dir(config)}")
